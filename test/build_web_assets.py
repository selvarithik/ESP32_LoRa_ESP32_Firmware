"""Deterministic PROGMEM gzip assets; --check detects stale generated content."""
from pathlib import Path
import gzip
import re
import sys

root = Path(__file__).resolve().parents[1]
parts = ['// Generated by test/build_web_assets.py; do not edit.\n#pragma once\n#include <Arduino.h>\n']
for filename, delimiter, symbol in [('local_web_server.cpp', 'HTML', 'rootGzip'), ('mqtt_page.h', 'MQTT', 'mqttGzip'), ('access_page.h','ACCESS','accessGzip')]:
    source = (root / 'src/web' / filename).read_text(encoding='utf-8')
    html = re.search(r'R"' + delimiter + r'\(([\s\S]*?)\)' + delimiter + r'"', source)[1]
    compressed = gzip.compress(html.encode('utf-8'), compresslevel=9, mtime=0)
    parts.append('const uint8_t ' + symbol + '[] PROGMEM = {\n')
    for offset in range(0, len(compressed), 24):
        parts.append(','.join(str(x) for x in compressed[offset:offset+24]) + ',\n')
    parts.append('};\n')
    assert gzip.decompress(compressed).decode('utf-8') == html
output = ''.join(parts).encode('utf-8')
destination = root / 'src/web/web_assets_gzip.h'
if '--check' in sys.argv:
    assert destination.read_bytes() == output, 'Run python test/build_web_assets.py'
    print('PASS: generated gzip assets match all source pages')
else:
    destination.write_bytes(output)
    print('Generated all offline gzip assets')
